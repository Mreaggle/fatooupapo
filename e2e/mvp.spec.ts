test('autoria tem explicação e revisão local persistente', async ({ page }, testInfo) => {
  await page.goto('./?v=q4T7plSBdJE')
  const first = page.getByRole('article').first()
  await expect(first.getByText('Jones Manoel', { exact: true })).toBeVisible()
  await first.getByRole('button', { name: /explicar índice textual de autoria/i }).click()
  await expect(first.getByRole('tooltip')).toContainText('não de veracidade do fato')
  await expect(first.getByRole('tooltip')).toContainText('não uma probabilidade calibrada')
  await first.getByRole('button', { name: 'Revisar locutor' }).click()
  await first.getByLabel('Quem falou este trecho?').selectOption('Kim Kataguiri')
  await first.getByRole('button', { name: 'Salvar revisão' }).click()
  await expect(first.getByText('Kim Kataguiri', { exact: true })).toBeVisible()
  await expect(first.getByText(/revisado por você/)).toBeVisible()
  await page.reload()
  await expect(page.getByRole('article').first().getByText('Kim Kataguiri', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('revisao-locutor.png'), fullPage: false })
  await page.getByRole('article').first().getByRole('button', { name: 'Revisar locutor' }).click()
  await page.getByRole('article').first().getByRole('button', { name: 'Restaurar sugestão' }).click()
  await expect(page.getByRole('article').first().getByText('Jones Manoel', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
